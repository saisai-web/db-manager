use super::*;
use crate::dsl::parse;

const SHOP: &str = r#"
@title ショップ
customers "顧客" "会員"
  id     int pk auto "顧客ID"
  name   varchar(100) not null "氏名"
  email  varchar(255) unique
  active bool not null default true
orders "注文"
  id          bigint pk auto
  customer_id int not null -> customers.id on delete cascade
  placed      datetime not null default now()
  total       decimal(12,2) default 0
  index (customer_id)
"#;

fn ddl_of(src: &str, target: Target) -> Ddl {
    generate(&parse(src).unwrap(), target, &DdlOptions::default())
}

#[test]
fn postgres_output_is_exact() {
    let ddl = ddl_of(SHOP, Target::Postgres);
    assert!(ddl.warnings.is_empty(), "{:?}", ddl.warnings);
    assert_eq!(
        ddl.sql,
        "\
-- ショップ(PostgreSQL)

CREATE TABLE customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT pk_customers PRIMARY KEY (id),
  CONSTRAINT uq_customers_email UNIQUE (email)
);

CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  customer_id INTEGER NOT NULL,
  placed TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  total NUMERIC(12,2) DEFAULT 0,
  CONSTRAINT pk_orders PRIMARY KEY (id),
  CONSTRAINT fk_orders_customer_id FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE
);

CREATE INDEX ix_orders_customer_id ON orders (customer_id);

COMMENT ON TABLE customers IS '顧客: 会員';

COMMENT ON COLUMN customers.id IS '顧客ID';

COMMENT ON COLUMN customers.name IS '氏名';

COMMENT ON TABLE orders IS '注文';
"
    );
}

#[test]
fn sqlite_uses_rowid_keys_and_inline_comments() {
    let ddl = ddl_of(SHOP, Target::Sqlite);
    assert!(ddl.warnings.is_empty(), "{:?}", ddl.warnings);
    assert!(
        ddl.sql
            .contains("id INTEGER PRIMARY KEY AUTOINCREMENT, -- 顧客ID\n"),
        "{}",
        ddl.sql
    );
    assert!(
        !ddl.sql.contains("pk_customers"),
        "the key is inline: {}",
        ddl.sql
    );
    assert!(ddl.sql.contains("-- 顧客: 会員\nCREATE TABLE customers"));
    assert!(!ddl.sql.contains("COMMENT"));
}

#[test]
fn each_target_gets_its_own_auto_increment_and_comment_style() {
    let get = |t| ddl_of(SHOP, t).sql;
    assert!(get(Target::MySql).contains("id INT NOT NULL AUTO_INCREMENT COMMENT '顧客ID'"));
    assert!(get(Target::MySql).contains(") DEFAULT CHARSET=utf8mb4 COMMENT='注文';"));
    assert!(get(Target::SqlServer).contains("id INT IDENTITY(1,1) NOT NULL"));
    assert!(get(Target::SqlServer).contains("sp_addextendedproperty"));
    assert!(get(Target::Oracle).contains("placed TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL"));
    assert!(get(Target::Oracle).contains("COMMENT ON COLUMN customers.id IS '顧客ID';"));
}

#[test]
fn comments_can_be_turned_off() {
    let opts = DdlOptions {
        comments: false,
        ..Default::default()
    };
    for t in Target::ALL {
        let sql = generate(&parse(SHOP).unwrap(), t, &opts).sql;
        assert!(!sql.contains("顧客"), "{t:?}: {sql}");
    }
}

#[test]
fn drop_first_goes_children_before_parents() {
    let opts = DdlOptions {
        drop_first: true,
        ..Default::default()
    };
    let d = parse(SHOP).unwrap();
    let pg = generate(&d, Target::Postgres, &opts).sql;
    assert!(
        pg.find("DROP TABLE IF EXISTS orders CASCADE;")
            < pg.find("DROP TABLE IF EXISTS customers CASCADE;")
    );
    let ora = generate(&d, Target::Oracle, &opts).sql;
    assert!(ora.contains("EXECUTE IMMEDIATE 'DROP TABLE orders CASCADE CONSTRAINTS'"));
    assert!(
        ora.contains("END;\n/\n"),
        "PL/SQL blocks end with a slash line"
    );
}

#[test]
fn a_reference_cycle_is_closed_with_alter_table_after_all_tables() {
    let src = "a\n  id int pk\n  b_id int -> b.id\nb\n  id int pk\n  a_id int -> a.id\n";
    let sql = ddl_of(src, Target::Postgres).sql;
    let (create_b, alter) = (
        sql.find("CREATE TABLE b").unwrap(),
        sql.find("ALTER TABLE a").unwrap(),
    );
    assert!(create_b < alter, "{sql}");
    assert!(
        sql.contains(
            "ALTER TABLE a\n  ADD CONSTRAINT fk_a_b_id FOREIGN KEY (b_id) REFERENCES b (id);"
        ),
        "{sql}"
    );
    assert!(
        sql.contains("CONSTRAINT fk_b_a_id FOREIGN KEY (a_id) REFERENCES a (id)\n);"),
        "b -> a is inline: {sql}"
    );
    // SQLite cannot add constraints later, but it accepts references to tables not yet created
    let lite = ddl_of(src, Target::Sqlite).sql;
    assert!(!lite.contains("ALTER TABLE"), "{lite}");
}

#[test]
fn self_references_are_inline() {
    let sql = ddl_of(
        "emp\n  id int pk\n  boss int -> emp.id on delete set null\n",
        Target::Postgres,
    )
    .sql;
    assert!(
        sql.contains("FOREIGN KEY (boss) REFERENCES emp (id) ON DELETE SET NULL"),
        "{sql}"
    );
    assert!(!sql.contains("ALTER TABLE"));
}

#[test]
fn composite_keys_and_named_constraints() {
    let src = "p\n  a int pk\n  b int pk\nc\n  x int\n  y int\n  unique uq_xy (x, y)\n  index ix_x (x) unique\n  fk fk_c_p (x, y) -> p(a, b) on update cascade\n";
    let sql = ddl_of(src, Target::Postgres).sql;
    assert!(sql.contains("CONSTRAINT pk_p PRIMARY KEY (a, b)"));
    assert!(sql.contains("CONSTRAINT uq_xy UNIQUE (x, y)"));
    assert!(
        sql.contains("CONSTRAINT fk_c_p FOREIGN KEY (x, y) REFERENCES p (a, b) ON UPDATE CASCADE")
    );
    assert!(sql.contains("CREATE UNIQUE INDEX ix_x ON c (x);"));
}

#[test]
fn schema_names_qualify_tables_and_references() {
    let opts = DdlOptions {
        schema: "shop".into(),
        ..Default::default()
    };
    let d = parse(SHOP).unwrap();
    let sql = generate(&d, Target::Postgres, &opts).sql;
    assert!(sql.contains("CREATE SCHEMA IF NOT EXISTS shop;"));
    assert!(sql.contains("CREATE TABLE shop.orders ("));
    assert!(sql.contains("REFERENCES shop.customers (id)"));
    assert!(sql.contains("CREATE INDEX ix_orders_customer_id ON shop.orders (customer_id);"));
    let lite = generate(&d, Target::Sqlite, &opts);
    assert!(lite.sql.contains("CREATE TABLE orders ("));
    assert_eq!(lite.warnings.len(), 1);
}

