#[test]
fn foreign_key_indexes_are_added_only_where_missing() {
    let src = "p\n  id int pk\nc\n  id int pk\n  p_id int -> p\n  q_id int -> p\n  r_id int -> p\n  index (q_id, r_id)\n  fk_ok int\n";
    let opts = DdlOptions {
        index_foreign_keys: true,
        ..Default::default()
    };
    let d = parse(src).unwrap();
    let sql = generate(&d, Target::Postgres, &opts).sql;
    assert!(sql.contains("CREATE INDEX ix_c_p_id ON c (p_id);"), "{sql}");
    assert!(
        !sql.contains("ix_c_q_id ON"),
        "q_id leads an existing index: {sql}"
    );
    assert!(sql.contains("CREATE INDEX ix_c_r_id ON c (r_id);"), "{sql}");
    assert!(
        !generate(&d, Target::MySql, &opts).sql.contains("ix_c_p_id"),
        "MySQL adds them itself"
    );
}

#[test]
fn what_a_database_cannot_express_is_reported_not_silently_dropped() {
    let src = "p\n  id int pk\nc\n  id int pk\n  p int -> p on delete restrict on update cascade\n  t time\n  u uuid auto\n";
    let d = parse(src).unwrap();
    let w = |t| generate(&d, t, &DdlOptions::default()).warnings.join("\n");
    let ora = w(Target::Oracle);
    assert!(ora.contains("ON UPDATE"), "{ora}");
    assert!(ora.contains("TIME"), "{ora}");
    assert!(ora.contains("自動採番は整数"), "{ora}");
    assert!(w(Target::SqlServer).contains("RESTRICT"));
    assert!(!w(Target::Postgres).contains("ON UPDATE"));
}

