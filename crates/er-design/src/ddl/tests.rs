#[test]
fn sql_server_drops_cascade_actions_that_it_would_reject() {
    let src = "cat\n  id int pk\n  parent int -> cat.id on delete set null\nitem\n  id int pk\n  cat int -> cat.id on delete cascade\n";
    let d = parse(src).unwrap();
    let ms = generate(&d, Target::SqlServer, &DdlOptions::default());
    assert!(!ms.sql.contains("SET NULL"), "{}", ms.sql);
    assert!(
        ms.sql.contains("REFERENCES cat (id) ON DELETE CASCADE"),
        "the other one is fine: {}",
        ms.sql
    );
    assert_eq!(ms.warnings.len(), 1, "{:?}", ms.warnings);
    assert!(ms.warnings[0].contains("fk_cat_parent"));
    // 他の DB では、そのまま
    let pg = generate(&d, Target::Postgres, &DdlOptions::default());
    assert!(pg.sql.contains("ON DELETE SET NULL") && pg.warnings.is_empty());
}

#[test]
fn sql_server_drops_circular_foreign_keys_before_dropping_tables() {
    let src = "a\n  id int pk\n  b int -> b.id\nb\n  id int pk\n  a int -> a.id\n";
    let d = parse(src).unwrap();
    let opts = DdlOptions {
        drop_first: true,
        ..Default::default()
    };
    let sql = generate(&d, Target::SqlServer, &opts).sql;
    let drop_fk = sql
        .find("IF OBJECT_ID(N'fk_a_b', N'F') IS NOT NULL\n  ALTER TABLE a DROP CONSTRAINT fk_a_b;")
        .expect(&sql);
    assert!(
        drop_fk < sql.find("DROP TABLE IF EXISTS b").unwrap(),
        "{sql}"
    );
    let acyclic = parse("p\n  id int pk\nc\n  p int -> p.id\n").unwrap();
    assert!(
        !generate(&acyclic, Target::SqlServer, &opts)
            .sql
            .contains("OBJECT_ID")
    );
}
