//! CREATE TABLE 文と、表に付く制約。

use std::collections::HashSet;

use super::names::{describe, ident, ident_list, literal, qualified};
use super::native::{default_expr, native_type};
use super::{DdlOptions, Target, schema_for};
use crate::model::{Column, Design, ForeignKey, RefAction, Table};
use crate::types::DataType;

/// SQLite で `INTEGER PRIMARY KEY AUTOINCREMENT` と書ける表か(主キーが自動採番の整数 1 列)。
fn sqlite_rowid_key(t: &Table, target: Target) -> Option<&Column> {
    let pk = t.primary_key();
    let c = t.column(pk.first()?)?;
    (target == Target::Sqlite && pk.len() == 1 && c.auto && c.ty.is_integer()).then_some(c)
}

fn column_def(
    t: &Table,
    c: &Column,
    target: Target,
    opts: &DdlOptions,
    rowid: bool,
    w: &mut Vec<String>,
) -> String {
    let (ty, warn) = native_type(&c.ty, target);
    w.extend(warn.map(|m| format!("{}.{}: {m}", t.name, c.name)));
    let required = !c.nullable || c.primary;
    let mut auto = None;
    if c.auto {
        match (c.ty.is_integer(), target) {
            (false, _) => w.push(format!(
                "{}.{}: 自動採番は整数の列だけに使えます",
                t.name, c.name
            )),
            (true, Target::Postgres | Target::Oracle) => {
                auto = Some("GENERATED BY DEFAULT AS IDENTITY")
            }
            (true, Target::MySql) => auto = Some("AUTO_INCREMENT"),
            (true, Target::SqlServer) => auto = Some("IDENTITY(1,1)"),
            (true, Target::Sqlite) if rowid => auto = Some("PRIMARY KEY AUTOINCREMENT"),
            (true, Target::Sqlite) => w.push(format!(
                "{}.{}: SQLite の自動採番は、主キーが整数 1 列の表だけです",
                t.name, c.name
            )),
        }
    }
    let default = c.default.as_ref().filter(|_| auto.is_none()).map(|d| {
        let e = default_expr(d, target);
        let wrap = target == Target::MySql
            && matches!(c.ty, DataType::Text | DataType::Blob | DataType::Json);
        if wrap {
            format!("DEFAULT ({e})")
        } else {
            format!("DEFAULT {e}")
        }
    });
    let not_null = (required && !(rowid && auto.is_some())).then_some("NOT NULL".to_string());
    let auto = auto.map(String::from);
    let mut parts = vec![ident(target, &c.name), ty];
    let tail: [Option<String>; 3] = match target {
        Target::Oracle => [default, auto, not_null],
        Target::MySql | Target::Sqlite => [not_null, auto, default],
        Target::Postgres | Target::SqlServer => [auto, not_null, default],
    };
    parts.extend(tail.into_iter().flatten());
    if target == Target::MySql && opts.comments {
        let d = describe(&c.logical, &c.comment);
        if !d.is_empty() {
            parts.push(format!("COMMENT {}", literal(target, &d)));
        }
    }
    parts.join(" ")
}

fn action(
    target: Target,
    on_delete: bool,
    a: RefAction,
    w: &mut Vec<String>,
    what: &str,
) -> Option<String> {
    use RefAction::*;
    let sql = match (a, target) {
        (NoAction, _) => return None,
        (Restrict, Target::SqlServer) => {
            w.push(format!(
                "{what}: SQL Server には RESTRICT がないため、NO ACTION にしました"
            ));
            return None;
        }
        (Restrict, Target::Oracle) => return None,
        (Restrict, _) => "RESTRICT",
        (SetDefault, Target::MySql | Target::Oracle) => {
            w.push(format!(
                "{what}: この DB は SET DEFAULT に対応していないため、省略しました"
            ));
            return None;
        }
        (_, Target::Oracle) if !on_delete => {
            w.push(format!(
                "{what}: Oracle は ON UPDATE に対応していないため、省略しました"
            ));
            return None;
        }
        (a, _) => a.sql(),
    };
    Some(format!(
        "ON {} {sql}",
        if on_delete { "DELETE" } else { "UPDATE" }
    ))
}

/// 外部キーの定義(`CONSTRAINT .. FOREIGN KEY ..`)。参照先が壊れているときは、警告を出して `None`。
fn foreign_key(
    d: &Design,
    t: &Table,
    fk: &ForeignKey,
    no_cascade: bool,
    target: Target,
    opts: &DdlOptions,
    w: &mut Vec<String>,
) -> Option<String> {
    let name = t.fk_name(fk);
    let ref_cols = d.ref_columns(fk);
    let parent = d.table(&fk.ref_table);
    let ok = parent.is_some_and(|p| ref_cols.iter().all(|c| p.column(c).is_some()))
        && !ref_cols.is_empty()
        && ref_cols.len() == fk.columns.len()
        && fk.columns.iter().all(|c| t.column(c).is_some());
    if !ok {
        w.push(format!(
            "{}: 外部キー {name} は参照先を特定できないため、作りません",
            t.name
        ));
        return None;
    }
    let what = format!("{}: 外部キー {name}", t.name);
    let (on_delete, on_update) = if no_cascade {
        w.push(format!(
            "{what}: SQL Server は、自己参照・循環・複数の連鎖経路になる外部キーに ON DELETE / ON UPDATE を付けられないため、NO ACTION にしました"
        ));
        (RefAction::NoAction, RefAction::NoAction)
    } else {
        (fk.on_delete, fk.on_update)
    };
    let mut sql = format!(
        "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
        ident(target, &name),
        ident_list(target, &fk.columns),
        qualified(target, schema_for(target, opts), &fk.ref_table),
        ident_list(target, &ref_cols),
    );
    for a in [
        action(target, true, on_delete, w, &what),
        action(target, false, on_update, w, &what),
    ]
    .into_iter()
    .flatten()
    {
        sql.push(' ');
        sql.push_str(&a);
    }
    Some(sql)
}

/// CREATE TABLE 文と、あとから足す外部キー(参照先がまだ作られていないもの)。
pub fn create_table(
    d: &Design,
    t: &Table,
    target: Target,
    opts: &DdlOptions,
    created: &HashSet<&str>,
    rejected: &HashSet<(String, usize)>,
    w: &mut Vec<String>,
) -> (String, Vec<String>) {
    let rowid = sqlite_rowid_key(t, target);
    let qname = qualified(target, schema_for(target, opts), &t.name);
    let mut items: Vec<(String, String)> = Vec::new(); // (定義, SQLite の行末コメント)
    for c in &t.columns {
        let note = if target == Target::Sqlite && opts.comments {
            describe(&c.logical, &c.comment).replace('\n', " ")
        } else {
            String::new()
        };
        let is_rowid = rowid.is_some_and(|r| r.name == c.name);
        items.push((column_def(t, c, target, opts, is_rowid, w), note));
    }
    let pk = t.primary_key();
    if !pk.is_empty() && rowid.is_none() {
        items.push((
            format!(
                "CONSTRAINT {} PRIMARY KEY ({})",
                ident(target, &t.pk_name()),
                ident_list(target, &pk)
            ),
            String::new(),
        ));
    }
    for c in t
        .columns
        .iter()
        .filter(|c| c.unique && pk != [c.name.clone()])
    {
        let u = crate::model::UniqueKey {
            name: String::new(),
            columns: vec![c.name.clone()],
        };
        items.push((unique_def(t, &u, target), String::new()));
    }
    for u in &t.uniques {
        items.push((unique_def(t, u, target), String::new()));
    }
    let mut deferred = Vec::new();
    for (fi, fk) in t.foreign_keys.iter().enumerate() {
        let no_cascade = rejected.contains(&(t.name.clone(), fi));
        let Some(def) = foreign_key(d, t, fk, no_cascade, target, opts, w) else {
            continue;
        };
        let inline = target == Target::Sqlite
            || fk.ref_table == t.name
            || created.contains(fk.ref_table.as_str());
        if inline {
            items.push((def, String::new()));
        } else {
            deferred.push(format!("ALTER TABLE {qname}\n  ADD {def};"));
        }
    }

    let mut sql = String::new();
    let desc = describe(&t.logical, &t.comment);
    if target == Target::Sqlite && opts.comments && !desc.is_empty() {
        sql.push_str(&format!("-- {}\n", desc.replace('\n', " ")));
    }
    sql.push_str(&format!("CREATE TABLE {qname} (\n"));
    let last = items.len().saturating_sub(1);
    for (i, (def, note)) in items.iter().enumerate() {
        sql.push_str("  ");
        sql.push_str(def);
        if i != last {
            sql.push(',');
        }
        if !note.is_empty() {
            sql.push_str(&format!(" -- {note}"));
        }
        sql.push('\n');
    }
    sql.push(')');
    if target == Target::MySql {
        sql.push_str(" DEFAULT CHARSET=utf8mb4");
        if opts.comments && !desc.is_empty() {
            sql.push_str(&format!(" COMMENT={}", literal(target, &desc)));
        }
    }
    sql.push(';');
    (sql, deferred)
}

fn unique_def(t: &Table, u: &crate::model::UniqueKey, target: Target) -> String {
    format!(
        "CONSTRAINT {} UNIQUE ({})",
        ident(target, &t.unique_name(u)),
        ident_list(target, &u.columns)
    )
}
