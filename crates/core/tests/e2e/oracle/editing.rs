//! テーブルの編集(楽観的ロックによる競合の検出)。

use sqltool_core::*;

use super::Ora;
use crate::common::*;

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn table_editing_with_optimistic_conflict_detection() {
    let mut o = Ora::start(ora!(), EnvLabel::Dev).await;
    o.h.exec(o.tab, "create table people (id number generated by default as identity (start with 100) primary key, name varchar2(50), note varchar2(100)); insert into people (id, name, note) values (1, 'Alice', null); insert into people (id, name, note) values (2, 'Bob', 'x')").await;
    o.h.core.send(Command::OpenTable {
        tab: o.tab,
        table: o.table("PEOPLE"),
    });
    let evs =
        o.h.until(|e| matches!(e, Event::ExecutionFinished { .. }))
            .await;
    let r = result_handle(&evs);
    let EditAccess::Editable(source) = r.edit_access() else {
        panic!("{:?}", r.edit_access())
    };
    assert_eq!(source.key, ["ID"]);

    let orig = |row: u64, col: usize| {
        r.read_row_blocking(row).unwrap().unwrap()[col]
            .clone()
            .map(|b| String::from_utf8(b).unwrap())
    };
    let names: Vec<String> = r.columns().iter().map(|c| c.name.clone()).collect();
    let prepare = |o: &mut Ora, b: &EditBuffer| {
        o.h.core.send(Command::PrepareEdit {
            tab: o.tab,
            result: r.id(),
            changes: b.to_changes(source, &names, orig),
        });
    };

    // 元が NULL のセルを変えて、削除と追加も 1 回で保存する
    let mut b = EditBuffer::new();
    b.set_cell(0, 2, Some("filled".into()), &orig(0, 2));
    b.delete_row(1);
    let ix = b.add_insert(3);
    b.set_insert_cell(ix, 1, Some(Some("Carol".into())));
    prepare(&mut o, &b);
    let evs =
        o.h.until(|e| matches!(e, Event::EditPreview { .. } | Event::CommandFailed { .. }))
            .await;
    let Event::EditPreview {
        plan, statements, ..
    } = evs.last().unwrap().clone()
    else {
        panic!("{evs:?}")
    };
    assert!(
        statements
            .iter()
            .any(|s| s.sql.contains("DECODE(\"NOTE\", NULL, 1, 0) = 1")
                && s.sql.contains("\"ID\" = 1")),
        "{statements:?}"
    );
    o.h.core.send(Command::CommitEdit { tab: o.tab, plan });
    let done =
        o.h.until(|e| matches!(e, Event::EditCommitted { .. } | Event::EditRejected { .. }))
            .await
            .pop()
            .unwrap();
    assert!(
        matches!(done, Event::EditCommitted { statements: 3, .. }),
        "{done:?}"
    );
    let got = o
        .rows("select id, name, note from people order by id")
        .await;
    assert_eq!(
        got,
        [
            [cell("1"), cell("Alice"), cell("filled")],
            // id を指定しない追加は、IDENTITY が採番する
            [cell("100"), cell("Carol"), None]
        ]
    );

    // 他の接続が先に更新した行は、上書きしない(全体を取り消す)
    let mut b = EditBuffer::new();
    b.set_cell(0, 1, Some("mine".into()), &orig(0, 1));
    prepare(&mut o, &b);
    let evs = o.h.until(|e| matches!(e, Event::EditPreview { .. })).await;
    let Event::EditPreview { plan, .. } = evs.last().unwrap().clone() else {
        unreachable!()
    };
    o.h.exec(o.tab, "update people set name = 'theirs' where id = 1")
        .await;
    o.h.core.send(Command::CommitEdit { tab: o.tab, plan });
    let done =
        o.h.until(|e| matches!(e, Event::EditCommitted { .. } | Event::EditRejected { .. }))
            .await
            .pop()
            .unwrap();
    assert!(
        matches!(
            done,
            Event::EditRejected {
                reason: EditRejection::RowCount { actual: 0, .. },
                ..
            }
        ),
        "{done:?}"
    );
    assert_eq!(
        o.rows("select name from people where id = 1").await[0][0],
        cell("theirs")
    );
}
